#![cfg(not(feature = "napi"))]

use rmb_upper::*;

#[test]
fn formats_digit_and_unit_boundaries() {
    let cases = [
        ("1", "壹元整"),
        ("10", "壹拾元整"),
        ("11", "壹拾壹元整"),
        ("20", "贰拾元整"),
        ("101", "壹佰零壹元整"),
        ("110", "壹佰壹拾元整"),
        ("1001", "壹仟零壹元整"),
        ("1010", "壹仟零壹拾元整"),
        ("1100", "壹仟壹佰元整"),
        ("10000", "壹万元整"),
        ("10001", "壹万零壹元整"),
        ("10010", "壹万零壹拾元整"),
        ("10100", "壹万零壹佰元整"),
        ("11000", "壹万壹仟元整"),
        ("100000", "壹拾万元整"),
        ("100001", "壹拾万零壹元整"),
        ("100000000", "壹亿元整"),
        ("100000001", "壹亿零壹元整"),
        ("100010000", "壹亿零壹万元整"),
        ("10000100", "壹仟万零壹佰元整"),
        ("1000000000000", "壹万亿元整"),
        ("1000100010001", "壹万零壹亿零壹万零壹元整"),
        (
            "9999999999999999",
            "玖仟玖佰玖拾玖万玖仟玖佰玖拾玖亿玖仟玖佰玖拾玖万玖仟玖佰玖拾玖元整",
        ),
        ("0", "零元整"),
        ("0.01", "零元壹分"),
        ("0.10", "零元壹角"),
        ("0.11", "零元壹角壹分"),
        ("1.01", "壹元零壹分"),
        ("1.10", "壹元壹角"),
        ("1.11", "壹元壹角壹分"),
    ];

    for (input, expected) in cases {
        assert_eq!(format_decimal(input).unwrap(), expected, "input {input}");
    }
}

#[test]
fn handles_maximum_amount() {
    assert_eq!(
        format_cents(MAX_CENTS).unwrap(),
        "玖仟玖佰玖拾玖万玖仟玖佰玖拾玖亿玖仟玖佰玖拾玖万玖仟玖佰玖拾玖元玖角玖分"
    );
    assert_eq!(format_cents(MAX_CENTS + 1), Err(FormatError::TooLarge));
}
